    fun generateFloorWorldArtifacts(floor: Int): List<WorldArtifact> {
        val list = mutableListOf<WorldArtifact>()
        val totalArts = all200WorldArtifacts.size

        val coords = listOf(
            Pair(260f, -220f),
            Pair(-280f, 300f),
            Pair(380f, 280f),
            Pair(-360f, -260f),
            Pair(500f, -100f),
            Pair(-480f, 150f),
            Pair(180f, 450f),
            Pair(-220f, -480f),
            Pair(600f, 320f),
            Pair(-620f, -320f),
            Pair(420f, -500f),
            Pair(-450f, 520f),
            Pair(720f, 80f),
            Pair(-740f, -100f)
        )

        val count = 8 + (floor / 3).coerceAtMost(10)
        for (i in 0 until count) {
            val artIndex = ((floor * 13 + i * 17) % totalArts)
            val art = all200WorldArtifacts[artIndex].copy(
                level = floor
            )
            val posX = (Random.nextFloat() - 0.5f) * 1600f
            val posY = (Random.nextFloat() - 0.5f) * 1600f
            list.add(
                WorldArtifact(
                    id = UUID.randomUUID().toString(),
                    artifact = art,
                    x = posX,
                    y = posY
                )
            )
        }

        return list
    }
